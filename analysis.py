import cv2, numpy as np

def unit3_hough_lines(frame,
                      canny1=80, canny2=160,
                      rho=1, theta=np.pi/180,
                      thresh=70, min_len=60, max_gap=10):
    """Edges → Probabilistic Hough → draw lines."""
    gray  = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)
    blur  = cv2.GaussianBlur(gray, (5,5), 0)
    edges = cv2.Canny(blur, canny1, canny2)

    lines = cv2.HoughLinesP(edges, rho, theta,
                            threshold=thresh,
                            minLineLength=min_len,
                            maxLineGap=max_gap)

    out = frame.copy()
    if lines is not None:
        for (x1,y1,x2,y2) in lines[:,0,:]:
            cv2.line(out, (x1,y1), (x2,y2), (0,255,255), 2)

    cv2.putText(out, "Unit-3: Hough Lines", (10,25),
                cv2.FONT_HERSHEY_SIMPLEX, 0.7, (0,255,255), 2)
    return out

