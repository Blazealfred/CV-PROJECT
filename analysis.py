import cv2, numpy as np

def unit1_edges_corners(frame):
    gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)

    # Canny edges
    edges = cv2.Canny(gray, 100, 200)
    edge_col = cv2.cvtColor(edges, cv2.COLOR_GRAY2BGR)

    # Overlay edges on original
    out = cv2.addWeighted(frame, 0.8, edge_col, 0.5, 0)

    # Corners (Shi–Tomasi)
    pts = cv2.goodFeaturesToTrack(gray, maxCorners=200, qualityLevel=0.01,
                                  minDistance=7, blockSize=7)
    if pts is not None:
        for p in np.int0(pts):
            x, y = p.ravel()
            cv2.circle(out, (x, y), 3, (0,255,0), -1)

    cv2.putText(out, "Unit-1: Canny + Corners",
                (10,25), cv2.FONT_HERSHEY_SIMPLEX, 0.7, (0,255,0), 2)
    return out

