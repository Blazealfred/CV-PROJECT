import cv2, numpy as np
from skimage.morphology import skeletonize

def unit2_regions_skeleton(frame):
    gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)
    blur = cv2.GaussianBlur(gray, (5,5), 0)

    # Binary mask (tweak C and blockSize if needed)
    mask = cv2.adaptiveThreshold(
        blur, 255,
        cv2.ADAPTIVE_THRESH_GAUSSIAN_C, cv2.THRESH_BINARY_INV,
        41, 5
    )

    # Clean small noise
    mask = cv2.morphologyEx(mask, cv2.MORPH_OPEN, np.ones((3,3), np.uint8), iterations=1)

    # Contours & centroids
    cnts, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    out = frame.copy()
    for c in cnts:
        if cv2.contourArea(c) < 500:   # ignore tiny blobs
            continue
        x,y,w,h = cv2.boundingRect(c)
        cv2.rectangle(out,(x,y),(x+w,y+h),(255,0,0),2)
        M = cv2.moments(c)
        if M["m00"] != 0:
            cx, cy = int(M["m10"]/M["m00"]), int(M["m01"]/M["m00"])
            cv2.circle(out,(cx,cy),3,(255,0,0),-1)

    # Skeleton (thin the mask)
    skel = skeletonize((mask>0).astype(np.uint8)).astype(np.uint8)*255
    skel_col = cv2.cvtColor(skel, cv2.COLOR_GRAY2BGR)

    # Overlay skeleton
    out = cv2.addWeighted(out, 0.8, skel_col, 0.5, 0)
    cv2.putText(out, "Unit-2: Regions + Skeleton", (10,25),
                cv2.FONT_HERSHEY_SIMPLEX, 0.7, (255,0,0), 2)
    return out

