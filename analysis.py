import cv2, numpy as np

class OpticalFlowLK:
    def __init__(self,
                 max_corners=300, qlevel=0.01, mindist=7,
                 win=(21,21), max_level=3):
        self.prev_gray = None
        self.prev_pts  = None
        self.params_gftt = dict(maxCorners=max_corners,
                                qualityLevel=qlevel,
                                minDistance=mindist,
                                blockSize=7)
        self.params_lk = dict(winSize=win,
                              maxLevel=max_level,
                              criteria=(cv2.TERM_CRITERIA_EPS |
                                        cv2.TERM_CRITERIA_COUNT, 30, 0.01))
    def reset(self):
        self.prev_gray, self.prev_pts = None, None

    def step(self, frame):
        gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)
        vis  = frame.copy()

        # Initialize with corners on first frame (or when we lose many points)
        if self.prev_gray is None or self.prev_pts is None or len(self.prev_pts) < 50:
            self.prev_gray = gray
            self.prev_pts  = cv2.goodFeaturesToTrack(gray, **self.params_gftt)
            cv2.putText(vis, "Unit-4: Optical Flow (init)",
                        (10,25), cv2.FONT_HERSHEY_SIMPLEX, 0.7, (0,165,255), 2)
            return vis

        next_pts, st, err = cv2.calcOpticalFlowPyrLK(
            self.prev_gray, gray, self.prev_pts, None, **self.params_lk
        )

        if next_pts is not None:
            good_new = next_pts[st==1]
            good_old = self.prev_pts[st==1]

            # Draw motion arrows
            for (x2,y2),(x1,y1) in zip(good_new, good_old):
                x1,y1,x2,y2 = int(x1),int(y1),int(x2),int(y2)
                if (x1-x2)**2 + (y1-y2)**2 < 1:  # ignore tiny motion
                    continue
                cv2.arrowedLine(vis, (x1,y1), (x2,y2), (0,165,255), 2, tipLength=0.3)

            # Update state
            self.prev_pts  = good_new.reshape(-1,1,2)
            self.prev_gray = gray

        cv2.putText(vis, "Unit-4: Optical Flow", (10,25),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.7, (0,165,255), 2)
        return vis

flow = OpticalFlowLK()

