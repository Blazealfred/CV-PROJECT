def run_on_video(in_path, out_name="pipeline_output.mp4", resize_width=960, duration_sec=10):
    assert os.path.exists(in_path), f"Input not found: {in_path}"
    cap = cv2.VideoCapture(in_path)
    assert cap.isOpened(), f"Cannot open: {in_path}"
    W = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
    H = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
    FPS = cap.get(cv2.CAP_PROP_FPS) or 30.0
    N  = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))

    # For speed, optionally downscale frames (keeps aspect ratio)
    if resize_width and resize_width < W:
        out_w = resize_width
        out_h = int(H * (resize_width / W))
    else:
        out_w, out_h = W, H

    raw_path  = f"/content/output/_raw_{out_name}"
    show_path = f"/content/output/{out_name}"
    writer = cv2.VideoWriter(raw_path, cv2.VideoWriter_fourcc(*'mp4v'), FPS, (out_w, out_h))

    # Reset flow tracker each run
    if MODULES.get("unit4"):
        try: flow.reset()
        except NameError: pass

    max_frames = int(min(N, FPS * duration_sec))
    i = 0
    while i < max_frames:
        ok, frame = cap.read()
        if not ok: break
        if out_w != W:
            frame = imutils.resize(frame, width=out_w)
        processed = apply_pipeline(frame)
        writer.write(processed)
        i += 1
        if i % int(FPS*2) == 0:
            print(f" .. processed {i}/{max_frames} frames")
    cap.release()
    writer.release()
    print(f"✅ wrote {i} frames to {raw_path}")

